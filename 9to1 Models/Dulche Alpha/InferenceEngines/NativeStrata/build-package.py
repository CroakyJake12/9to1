#!/usr/bin/env python3
"""Verify/extract the exact public donor and build the bundled fork. No models or tests.

Preparation is default; --build requires the actual CUDA toolkit and never ships a CPU stub.

The build is profile-aware:
  * legacy (default)  - the maintained ro99/strata pin (strata-source-lock.json) with the
                        in-process C ABI worker (dulche-strata-worker). Linux x64 only.
  * candidate           - the owner-designated Niko1221/Strata v0.2.2 pin with the candidate
                        sub-process relay worker (dulche-strata-candidate-worker) that drives the
                        upstream `strata --serve` engine. Linux x64 or Windows x64.

The receipt records the exact selected lock (SHA-256), profile, target (Linux x64 / Windows x64),
toolchain versions, upstream commit/tree and the installed binary digest. A Windows target validates
a PE32+ x64 image; a Linux target validates an ELF64 x86_64 image. A Linux worker is never labeled
Windows-capable and vice versa.
"""
import argparse
import hashlib
import json
import os
import pathlib
import re
import shutil
import struct
import subprocess
import tarfile

PROFILES = ("legacy", "candidate")

# The verified candidate pin (v0.2.2). The EOL CRLF->LF export transform is authorized ONLY for the
# exact official 16 archive members below, and only for locks tied to this exact source pin/tree.
# A self-declared eolExportNormalized name is never accepted by itself; a legacy lock (empty exception
# set) is verified unchanged.
CANDIDATE_COMMIT_PIN = "011c9e600a93bbc9fd451c563501b5831c32bbca"
CANDIDATE_TREE_PIN = "539755e6d6b799bd75a47225befc786c436f6d8b"
