#!/usr/bin/env python3
"""Verify/extract the exact public donor and build the bundled fork. No models or tests.

Preparation is default; --build requires the actual CUDA toolkit and never ships a CPU stub.

The build is profile-aware:
  * legacy (default)  - the maintained ro99/strata pin (strata-source-lock.json) with the
                        in-process C ABI worker (dulche-strata-worker). Linux x64 only.
  * candidate           - the owner-designated Niko1221/Strata v0.2.1 pin with the candidate
                        sub-process relay worker (dulche-strata-candidate-worker) that drives the
                        upstream `strata --serve` engine. Linux x64 or Windows x64.

The receipt records the exact selected lock (SHA-256), profile, target (Linux x64 / Windows x64),
toolchain versions, upstream commit/tree and the installed binary digest. A Windows target validates
a PE32+ x64 image; a Linux target validates an ELF64 x86_64 image. A Linux worker is never labeled
Windows-capable and vice versa.
"""
import argparse
import hashlib
import json
import pathlib
import re
import shutil
import struct
import subprocess
import tarfile

PROFILES = ("legacy", "candidate")
DEFAULT_LOCKS = {
    # The candidate lock is generated by prepare-upstream-update.py and kept out of the source
    # tree; it must be supplied explicitly via --lock for a candidate build.
    "legacy": None,  # -> overlay/strata-source-lock.json
    "candidate": None,  # required via --lock
}


def verify_linux_x64_elf(body):
    # ELF OSABI 0 is the normal System V encoding used by Linux executables.
    # CMake separately proves the configured target system is Linux; inspect actual output too.
    if (len(body) < 64 or body[:4] != b"\x7fELF" or body[4:7] != b"\x02\x01\x01"
            or body[7] not in (0, 3) or int.from_bytes(body[16:18], "little") not in (2, 3)
            or int.from_bytes(body[18:20], "little") != 62 or int.from_bytes(body[20:24], "little") != 1):
        raise ValueError("Actual worker must be an ELF64 little-endian x86_64 Linux target")
    return {"elfClass": 64, "endianness": "little", "machine": 62, "targetSystem": "linux-x64"}


def verify_windows_x64_pe(body):
    """Actual worker must be a PE32+ (x64) Windows image: MZ + PE\\0\\0, machine AMD64."""
    if len(body) < 0x40 or body[:2] != b"MZ":
        raise ValueError("Actual worker must be a Windows x64 PE image (MZ signature)")
    pe_off = struct.unpack_from("<I", body, 0x3C)[0]
    if pe_off + 28 > len(body) or body[pe_off:pe_off + 4] != b"PE\x00\x00":
        raise ValueError("Invalid PE signature")
    machine = struct.unpack_from("<H", body, pe_off + 4)[0]
    if machine != 0x8664:  # IMAGE_FILE_MACHINE_AMD64
        raise ValueError("Actual worker is not a Windows x64 machine type")
    opt_magic = struct.unpack_from("<H", body, pe_off + 24)[0]
    if opt_magic != 0x20B:  # PE32+ (x64) optional header
        raise ValueError("Actual worker is not a PE32+ (x64) image")
    return {"peClass": "PE32+", "machine": 0x8664, "targetSystem": "windows-x64"}


BINARY_CHECKERS = {
    "linux-x64": verify_linux_x64_elf,
    "windows-x64": verify_windows_x64_pe,
}


def tool_version(cmd, pattern):
    try:
        out = subprocess.run([cmd, "--version"], check=True, capture_output=True, text=True).stdout
    except Exception:
        return None
    m = re.search(pattern, out)
    return m.group(0) if m else out.splitlines()[0] if out.strip() else None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--archive", type=pathlib.Path, required=True)
    parser.add_argument("--work", type=pathlib.Path, required=True)
    parser.add_argument("--install", type=pathlib.Path)
    parser.add_argument("--cmake", default="cmake")
    parser.add_argument("--nvcc", default="nvcc")
    parser.add_argument("--build", action="store_true")
    parser.add_argument("--profile", choices=PROFILES, default="legacy")
    parser.add_argument("--lock", type=pathlib.Path, help="Explicit lock JSON (required for candidate).")
    parser.add_argument("--target", choices=("linux-x64", "windows-x64"), default="linux-x64")
    parser.add_argument("--ggml-dir", type=pathlib.Path,
                        help="Verified local llama.cpp checkout for STRATA_GGML_DIR (candidate).")
    args = parser.parse_args()
    overlay = pathlib.Path(__file__).resolve().parent

    if args.lock is not None:
        lock_path = args.lock
    elif args.profile == "legacy":
        lock_path = overlay / "strata-source-lock.json"
    else:
        raise ValueError("candidate profile requires --lock (generated by prepare-upstream-update.py)")

    lock = json.loads(lock_path.read_text())
    selected_lock_sha = hashlib.sha256(lock_path.read_bytes()).hexdigest()

    archive = args.archive.read_bytes()
    if len(archive) != lock["archive"]["bytes"] or hashlib.sha256(archive).hexdigest() != lock["archive"]["sha256"]:
        raise ValueError("Exact donor archive mismatch")
    if args.work.exists():
        raise ValueError("A new empty work path is required; existing source is never overwritten")
    expected = {row["path"]: row for row in lock["rows"]}
    verified = {}
    with tarfile.open(args.archive, "r:gz") as source:
        roots = set()
        for member in source.getmembers():
            name = pathlib.PurePosixPath(member.name)
            if name.is_absolute() or ".." in name.parts or not name.parts:
                raise ValueError("Unsafe archive path")
            roots.add(name.parts[0])
            if member.isdir():
                continue
            if not member.isfile() or len(name.parts) < 2:
                raise ValueError("Only the pinned regular source files are admitted")
            relative = pathlib.PurePosixPath(*name.parts[1:]).as_posix()
            row = expected.get(relative)
            if row is None or relative in verified or member.size != row["bytes"]:
                raise ValueError("Unexpected source member")
            original = source.extractfile(member)
            if original is None:
                raise ValueError("Missing original source body")
            with original:
                body = original.read(row["bytes"] + 1)
            blob = hashlib.sha1(b"blob " + str(len(body)).encode() + b"\0" + body).hexdigest()
            if len(body) != row["bytes"] or blob != row["gitBlobSha"] or hashlib.sha256(body).hexdigest() != row["sha256"]:
                raise ValueError("Pinned source body mismatch: " + relative)
            verified[relative] = body
        if len(roots) != 1 or set(verified) != set(expected) or len(verified) != lock["blobCount"]:
            raise ValueError("Incomplete immutable donor closure")
    args.work.mkdir(parents=True)
    upstream = args.work / "upstream"
    for relative, body in verified.items():
        destination = upstream / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(body)
    fork = args.work / "dulche-fork"
    fork.mkdir()
    if args.profile == "legacy":
        files = ["CMakeLists.txt", "dulche_strata.h", "dulche_strata.cpp", "dulche_strata_worker.cpp"]
    else:
        files = ["CMakeLists.txt", "dulche_strata.h", "dulche_strata_candidate_worker.cpp",
                 "strata_tokenizer_helper.py"]
    for filename in files:
        shutil.copyfile(overlay / filename, fork / filename)
    record = {"profile": args.profile, "target": args.target,
              "lock": str(lock_path), "lockSha256": selected_lock_sha,
              "origin": lock["origin"], "commit": lock["commit"], "tree": lock.get("gitCommitTree"),
              "archiveSha256": lock["archive"]["sha256"], "verifiedFiles": len(verified),
              "toolchain": {"cmake": tool_version(args.cmake, r"cmake version [\d.]+"),
                            "nvcc": tool_version(args.nvcc, r"release [\d.]+")},
              "qualification": "Verified source; no compilation, CUDA availability or model execution inferred."}
    if args.profile == "candidate":
        # Record the pinned dependency closure (llama.cpp/ggml) digests so a reproducible offline build
        # can be checked against the exact pin rather than silently falling back to unverified FetchContent.
        dep_lock = overlay / "llama.cpp-dependency-lock.json"
        if dep_lock.exists():
            dep = json.loads(dep_lock.read_text())
            record["dependencyLockSha256"] = hashlib.sha256(dep_lock.read_bytes()).hexdigest()
            record["dependencyPinnedCommit"] = dep.get("pinnedCommit")
        if args.ggml_dir is not None:
            ggml_marker = pathlib.Path(args.ggml_dir) / "CMakeLists.txt"
            if not ggml_marker.exists():
                raise ValueError("STRATA_GGML_DIR does not point to a real llama.cpp checkout")
            record["ggmlDir"] = str(args.ggml_dir)
    (args.work / "source-verification.json").write_text(json.dumps(record, indent=2) + "\n")
    if not args.build:
        return
    if args.install is None or args.install.exists():
        raise ValueError("Build requires a new install directory")

    cmake_args = [args.cmake, "-S", str(fork), "-B", str(args.work / "build"),
                  "-DDULCHE_STRATA_PROFILE=" + args.profile,
                  "-DDULCHE_STRATA_UPSTREAM=" + str(upstream),
                  "-DCMAKE_BUILD_TYPE=Release",
                  "-DCMAKE_INSTALL_PREFIX=" + str(args.install)]
    if args.profile == "candidate":
        cmake_args += ["-DSTRATA_ENABLE_CUDA=ON", "-DSTRATA_NATIVE_EXPERTS=ON"]
        if args.ggml_dir is not None:
            cmake_args += ["-DSTRATA_GGML_DIR=" + str(args.ggml_dir)]
        if args.target == "windows-x64":
            cmake_args += ["-DCMAKE_SYSTEM_NAME=Windows"]
    else:
        # legacy requires CUDA 12.8+; no CPU stub is ever shipped as an available engine.
        nvcc = shutil.which(args.nvcc)
        if nvcc is None:
            raise ValueError("CUDA toolkit is required; no CPU stub is shipped as an available Strata engine")
        version = subprocess.run([nvcc, "--version"], check=True, capture_output=True, text=True).stdout
        match = re.search(r"release (\d+)\.(\d+)", version)
        if match is None or tuple(map(int, match.groups())) < (12, 8):
            raise ValueError("Pinned donor requires CUDA 12.8 or newer")
        cmake_args += ["-DCMAKE_CUDA_COMPILER=" + nvcc, "-DSTRATA_ENABLE_NCCL=OFF"]

    subprocess.run(cmake_args, check=True)
    subprocess.run([args.cmake, "--build", str(args.work / "build"), "--parallel", "1"], check=True)

    checker = BINARY_CHECKERS[args.target]
    if args.profile == "legacy":
        binary_rel = pathlib.Path("dulche-strata-worker")
    else:
        # candidate relay worker (the upstream `strata` engine is installed as a sibling binary)
        binary_rel = pathlib.Path("dulche-strata-candidate-worker")
    build_dir = args.work / "build"
    # Windows multi-config generators place the artifact under <config>/; single-config (Make/Ninja)
    # place it at the build root. Resolve the ACTUAL built artifact, never assume a single layout.
    def resolve_built(rel):
        candidates = [build_dir / rel, build_dir / "Release" / rel,
                      build_dir / "RelWithDebInfo" / rel, build_dir / "Debug" / rel]
        for c in candidates:
            if c.exists():
                return c
        raise ValueError("Built binary not found in the build output: " + str(rel))
    built = resolve_built(binary_rel)
    record["target"] = checker(built.read_bytes())
    subprocess.run([args.cmake, "--install", str(build_dir)], check=True)
    binary = args.install / "runtimes" / args.target / "native" / binary_rel.name
    if not binary.exists() or binary.read_bytes() != built.read_bytes():
        raise ValueError("Installed worker must be the exact inspected build output")
    checker(binary.read_bytes())
    record["workerSha256"] = hashlib.sha256(binary.read_bytes()).hexdigest()
    record["workerBytes"] = binary.stat().st_size
    if args.profile == "candidate":
        # Installed engine + bundled helper + dependency-closure digests are part of the receipt, so
        # the exact installed closure is reproducible and auditable, not just the worker hash.
        engine = args.install / "runtimes" / args.target / "engine" / (("strata" + (".exe" if args.target == "windows-x64" else "")))
        if not engine.exists():
            raise ValueError("Installed engine binary is missing from the receipt closure: " + str(engine))
        record["engineSha256"] = hashlib.sha256(engine.read_bytes()).hexdigest()
        record["engineBytes"] = engine.stat().st_size
        helper = args.install / "runtimes" / args.target / "native" / "strata_tokenizer_helper.py"
        if helper.exists():
            record["helperSha256"] = hashlib.sha256(helper.read_bytes()).hexdigest()
            record["helperBytes"] = helper.stat().st_size
    record["qualification"] = "Actual build artifact; runtime CUDA-device/model/capability acceptance is separately required."
    shutil.copyfile(lock_path, args.install / "strata-source-lock.json")
    (args.install / "strata-build-receipt.json").write_text(json.dumps(record, indent=2) + "\n")


if __name__ == "__main__":
    main()
