    public async Task OpenAttachmentAsync(string blockId)
    {
        var block = FindBlock(blockId);
        if (block?.AttachmentId is null)
            return;
        if (_session is not ContractSessionAdapter adapter)
        {
            Set("StatusText", $"Attachment: {block.AttachmentName} ({block.AttachmentSize} bytes)");
            return;
        }
        try
        {
            var resolution = await adapter.ResolveAttachmentAsync(block.AttachmentId);
            byte[]? bytes = resolution.EmbeddedBytes;
            if (bytes is null && resolution.SidecarPath is { Length: > 0 } sidecar && File.Exists(sidecar))
                bytes = await File.ReadAllBytesAsync(sidecar);
            if (bytes is null)
            {
                Set("StatusText", "Attachment unavailable: " + FirstLine(resolution.Message));
                return;
            }
            var tempPath = Path.Combine(
                Path.GetTempPath(), "9to1-boards",
                $"{resolution.AttachmentId}-{SanitizeFileName(block.AttachmentName ?? "attachment")}");
            Directory.CreateDirectory(Path.GetDirectoryName(tempPath)!);
            await File.WriteAllBytesAsync(tempPath, bytes);
            try
            {
                System.Diagnostics.Process.Start(new System.Diagnostics.ProcessStartInfo(tempPath)
                {
                    UseShellExecute = true,
                });
            }
            catch (Exception launchError)
            {
                Set("StatusText", $"Attachment resolved to {tempPath} (open failed: {FirstLine(launchError.Message)})");
                return;
            }
            Set("StatusText", $"Attachment opened: {tempPath}");
        }
        catch (Exception error)
        {
            Set("StatusText", "Open attachment failed: " + FirstLine(error.Message));
        }
    }

