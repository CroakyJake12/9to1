    public async ValueTask DispatchAsync(string command, object? parameter, CancellationToken cancellationToken = default)
    {
        if (_disposed || SessionIsDisposed) return;
        if (!CanEdit && command is ("ToggleEditView" or "ShowLanding" or "OpenRecentBoard" or "OpenRecentPage" or
            "NewBoard" or "NewMenu" or "OpenBoard" or "SaveBoard" or "SaveAsBoard" or "FileMenu" or
            "OverflowMenu" or "BoardProperties" or "CloseWindow" or "ApplySectionIconChoice" or
            "ApplySectionIconColor" or "UseThemeSectionIconColor"))
        {
            Set("StatusText", "This board source is open read-only.");
            return;
        }
        if ((!CanSwitchBoard && command is ("ShowLanding" or "OpenRecentBoard" or "OpenRecentPage" or "OpenBoard")) ||
            (!CanSaveAs && command == "SaveAsBoard") ||
            (!CanSwitchBoard && command == "NewBoard" && _homeBoardCreationHost is null))
        {
            Set("StatusText", "This board source does not grant that action.");
            return;
        }
        if (!CanSwitchBoard && command == "NewBoard" && _homeCreationOperationInProgress)
        {
            Set("StatusText", "A Board creation is already in progress.");
            return;
        }
        if (!CanSwitchBoard && command == "NewBoard" && _homeBoardCreationHost?.HasUnresolvedCreation == true)
        {
            Set("StatusText", _homeBoardCreationHost.CanRetryCreationSettlement
                ? "Board created; saving is still finishing. Retry before opening it."
                : _homeBoardCreationHost.CanOpenRecordedBoard
                    ? "Board found; its save status could not be confirmed. Open the saved Board to continue."
                : _homeBoardCreationHost.CanRetryOpenCreatedBoard
                    ? "Board created, opening failed. Retry opens the same Board."
                    : "Unable to confirm whether this Board was saved. Creating another is disabled while Home checks.");
            return;
        }
        if (command == "ToggleEditView")
        {
            SetEditMode(!_isEditMode);
            return;
        }
        if (command == "ShowLanding")
        {
            SetLanding(true);
            LandingRequested?.Invoke();
            return;
        }
        if (!_isEditMode && !AllowedWhileViewing(command))
        {
            Set("StatusText", "View mode: switch to Edit to change this board.");
            return;
        }
        if (await DispatchCuiContextAsync(command, cancellationToken)) return;
        if (await DispatchTextRangeAsync(command, cancellationToken)) return;
        switch (command)
        {
            case "CloseSectionIconPicker":
                CloseSectionIconPicker();
                break;
            case "SuggestSectionIcon":
                await SuggestSectionIconAsync(cancellationToken);
                break;
            case "ApplyGeneratedSectionIcon" when parameter is string generatedIndex:
                await ApplyGeneratedSectionIconAsync(generatedIndex, cancellationToken);
                break;
            case "ApplySectionIconChoice" when parameter is string iconKey && _sectionIconPickerSectionId is { } iconSectionId:
                var iconSection = _session.Document.Sections.FirstOrDefault(item => item.Id == iconSectionId);
                if (iconSection is not null)
                    await SetSectionIconAsync(iconSectionId, iconKey, iconSection.IconColor, cancellationToken);
                break;
            case "ApplySectionIconColor" when parameter is string iconColor && _sectionIconPickerSectionId is { } colorSectionId:
                var colorSection = _session.Document.Sections.FirstOrDefault(item => item.Id == colorSectionId);
                if (colorSection is not null)
                    await SetSectionIconColorAsync(colorSection, iconColor, cancellationToken);
                break;
            case "UseThemeSectionIconColor" when _sectionIconPickerSectionId is { } themeSectionId:
                var themeSection = _session.Document.Sections.FirstOrDefault(item => item.Id == themeSectionId);
                if (themeSection is not null)
                    await SetSectionIconColorAsync(themeSection, null, cancellationToken);
                break;
            case "NewBoard":
                if (_homeBoardCreationHost is null) NewBoardRequested?.Invoke();
                else await CreateAndOpenHomeBoardAsync(cancellationToken);
                break;
            case "RetryOpenCreatedBoard":
                await RetryOpenCreatedHomeBoardAsync(cancellationToken);
                break;
            case "RetryBoardCreationSettlement":
                await RetryHomeBoardCreationSettlementAsync(cancellationToken);
                break;
            case "CheckSavedBoard":
                await InspectHomeBoardCreationAsync(cancellationToken);
                break;
            case "OpenRecordedBoard":
                await OpenRecordedHomeBoardAsync(cancellationToken);
                break;
            case "NewMenu":
                NewMenuRequested?.Invoke();
                break;
            case "OpenBoard":
                await OpenBoardDispatchAsync(cancellationToken);
                break;
            case "OpenRecentBoard":
                if (parameter is RecentBoardCard board && _allRecentBoards.Any(item => ReferenceEquals(item, board)) && board.IsAvailable && OpenBoardPathAsync is not null)
                    await OpenBoardPathAsync(board.Path, null);
                break;
            case "OpenRecentPage":
                if (parameter is RecentPageCard recentPage && _allRecentPages.Any(item => ReferenceEquals(item, recentPage)) && OpenBoardPathAsync is not null)
                    await OpenBoardPathAsync(recentPage.Path, recentPage.PageId);
                break;
            case "SaveBoard":
                Set("SaveStateText", "Saving…");
                await _session.SaveAsync(cancellationToken);
                Set("StatusText", _session.Status);
                Set("SaveStateText", MapSaveState(_session.Status));
                RefreshAfterEdit();
                break;
            case "SaveAsBoard":
                var basePath = _session.FilePath ?? "memory://boards/default";
                var copyPath = basePath.EndsWith(".9to1board", StringComparison.OrdinalIgnoreCase)
                    ? basePath[..^".9to1board".Length] + " (copy).9to1board"
                    : basePath + "-copy";
                await _session.SaveAsAsync(copyPath, cancellationToken);
                PushDocumentToBindings();
                RequestRebuild();
                break;
            case "AddBlock":
                CurrentPage().Blocks.Add(new RichBoardBlock { Kind = "paragraph", Text = "New block" });
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "AddSection":
                if (_session is ContractSessionAdapter sectionAdapter)
                {
                    var sectionId = await sectionAdapter.AddSectionAsync(cancellationToken: cancellationToken);
                    var addedSection = _session.Document.Sections.First(sectionItem => sectionItem.Id == sectionId);
                    _selectedSectionId = sectionId;
                    _selectedPageId = addedSection.Pages[0].Id;
                    SelectExistingBlock(addedSection.Pages[0]);
                    SyncSelectedInkView();
                    PushDocumentToBindings();
                    RequestRebuild();
                    NavRebuildRequested?.Invoke();
                    break;
                }
                var section = new RichBoardSection { Title = $"Section {_session.Document.Sections.Count + 1}" };
                section.Pages.Add(new RichBoardPage { Title = "New page" });
                _session.Document.Sections.Add(section);
                _selectedSectionId = section.Id;
                _selectedPageId = section.Pages[0].Id;
                SelectExistingBlock(section.Pages[0]);
                SyncSelectedInkView();
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "AddPage":
                if (_session is ContractSessionAdapter pageAdapter)
                {
                    var pageId = await pageAdapter.AddPageAsync(CurrentSection().Id, cancellationToken: cancellationToken);
                    var createdPage = _session.Document.Sections.SelectMany(sectionItem => sectionItem.Pages)
                        .First(pageItem => pageItem.Id == pageId);
                    _selectedPageId = pageId;
                    SelectExistingBlock(createdPage);
                    SyncSelectedInkView();
                    PushDocumentToBindings();
                    RequestRebuild();
                    NavRebuildRequested?.Invoke();
                    break;
                }
                var page = new RichBoardPage { Title = $"Page {CurrentSection().Pages.Count + 1}" };
                CurrentSection().Pages.Add(page);
                _selectedPageId = page.Id;
                SelectExistingBlock(page);
                SyncSelectedInkView();
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "AddWritePage":
                await AddWritePageAsync(createNew: false, cancellationToken: cancellationToken);
                break;
            case "CreateWritePage":
                await AddWritePageAsync(createNew: true, cancellationToken: cancellationToken);
                break;
            case "AddCanvasPage":
                await AddEmbeddedArtifactPageAsync("canvas", HavenRichPageTypes.Canvas,
                    createNew: false, cancellationToken);
                break;
            case "CreateCanvasPage":
                await AddEmbeddedArtifactPageAsync("canvas", HavenRichPageTypes.Canvas,
                    createNew: true, cancellationToken);
                break;
            case "LinkCreatedEmbeddedPage":
                await LinkCreatedEmbeddedPageAsync(cancellationToken);
                break;
            case "AddSubpage":
                await AddSubpageAsync(_selectedSectionId, _selectedPageId);
                break;
            case "ToggleBold":
                await ToggleSelectedBlockTextFormatAsync(BoardTextFormat.Bold, cancellationToken);
                break;
            case "ToggleItalic":
                await ToggleSelectedBlockTextFormatAsync(BoardTextFormat.Italic, cancellationToken);
                break;
            case "ToggleUnderline":
                await ToggleSelectedBlockTextFormatAsync(BoardTextFormat.Underline, cancellationToken);
                break;
            case "ToggleStrike":
                await ToggleSelectedBlockTextFormatAsync(BoardTextFormat.StrikeThrough, cancellationToken);
                break;
            case "ToggleSub":
                ToggleBaseline("subscript");
                break;
            case "ToggleSup":
                ToggleBaseline("superscript");
                break;
            case "ClearFormat":
                ClearSelectedFormat();
                break;
            case "FontBigger":
                ScaleSelectedFont(2);
                break;
            case "FontSmaller":
                ScaleSelectedFont(-2);
                break;
            case "AlignLeft": SetSelectedAlignment("left"); break;
            case "AlignCenter": SetSelectedAlignment("center"); break;
            case "AlignRight": SetSelectedAlignment("right"); break;
            case "AlignJustify": SetSelectedAlignment("justify"); break;
            case "IndentInc": ShiftSelectedIndent(1); break;
            case "IndentDec": ShiftSelectedIndent(-1); break;
            case "Undo":
                if (await _session.UndoAsync(cancellationToken))
                    Set("StatusText", _session.Status);
                else
                    Set("StatusText", "Nothing to undo");
                ReselectAfterUndo();
                RefreshAfterEdit();
                break;
            case "Redo":
                if (await _session.RedoAsync(cancellationToken))
                    Set("StatusText", _session.Status);
                else
                    Set("StatusText", "Nothing to redo");
                ReselectAfterUndo();
                RefreshAfterEdit();
                break;
            case "ManageStyles":
                StyleEditorRequested?.Invoke();
                break;
            case "FileMenu":
                FileMenuRequested?.Invoke();
                break;
            case "OverflowMenu":
                OverflowRequested?.Invoke();
                break;
            case "BoardProperties":
                BoardPropertiesRequested?.Invoke();
                break;
            case "CloseWindow":
                CloseWindowRequested?.Invoke();
                break;
            case "ToggleTheme":
                ThemeToggleRequested?.Invoke();
                break;
            case "ToggleCanvasLock":
                await ToggleCanvasLockAsync(cancellationToken);
                break;
            case "SetLayoutMode":
                await SetLayoutModeAsync(Convert.ToString(parameter, CultureInfo.InvariantCulture) ?? string.Empty, cancellationToken);
                break;
            case "AddInkDot":
                AddInkStroke();
                break;
            case "ClearInk":
                await ClearInkAsync(cancellationToken);
                break;
            case "SelectSection1":
                if (_session.Document.Sections.Count > 0)
                {
                    _selectedSectionId = _session.Document.Sections[0].Id;
                    _selectedPageId = CurrentSection().Pages.Count > 0 ? CurrentSection().Pages[0].Id : _selectedPageId;
                    SelectExistingBlock(CurrentPage());
                    SyncSelectedInkView();
                    PushDocumentToBindings();
                    RequestRebuild();
                }
                break;
            case "SelectSection2":
                if (_session.Document.Sections.Count > 1)
                {
                    _selectedSectionId = _session.Document.Sections[1].Id;
                    _selectedPageId = CurrentSection().Pages.Count > 0 ? CurrentSection().Pages[0].Id : _selectedPageId;
                    SelectExistingBlock(CurrentPage());
                    SyncSelectedInkView();
                    PushDocumentToBindings();
                    RequestRebuild();
                }
                break;
            case "SelectPage1":
                if (CurrentSection().Pages.Count > 0)
                {
                    _selectedPageId = CurrentSection().Pages[0].Id;
                    SelectExistingBlock(CurrentPage());
                    SyncSelectedInkView();
                    PushDocumentToBindings();
                    RequestRebuild();
                }
                break;
            case "SelectPage2":
                if (CurrentSection().Pages.Count > 1)
                {
                    _selectedPageId = CurrentSection().Pages[1].Id;
                    SelectExistingBlock(CurrentPage());
                    SyncSelectedInkView();
                    PushDocumentToBindings();
                    RequestRebuild();
                }
                break;
        }
    }

