// BoardsViewModel bridges the CUI Boards surface and IRichBoardSession.
// It is both the ICuiBindingContext (all {Binding ...} paths in Boards.cui)
// and the ICuiActionDispatcher (all action="..." commands in Boards.cui).
//
// Editing model: static CUI controls use legacy names (BoardTitleBox,
// HeadingBox, ParaBox, Check1Box...); dynamically rendered blocks use
// id-encoded names (t_{blockId}, done_{parentId}_{itemId},
// chk_{parentId}_{itemId}, cell_{blockId}_{r}_{c}, gx_/gv_/gc_ graph fields,
// gvp_ viewport fields, iw_/ialt_ image fields, dvth_/dvcl_ divider fields).
// Control ids generated by the contract never contain '_', so names are split
// on the LAST '_' (documented in BlockRenderer).

using System.ComponentModel;
using System.Runtime.CompilerServices;
using Avalonia.Controls;
using Avalonia.Input;
using CakeOS.Cui;

namespace CakeOS.Apps.Boards.App;

public sealed class BoardsViewModel : ICuiBindingContext, ICuiActionDispatcher, INotifyPropertyChanged
{
    private readonly IRichBoardSession _session;
    private readonly Dictionary<string, object?> _properties = new(StringComparer.OrdinalIgnoreCase);
    private string _selectedSectionId = "section-1";
    private string _selectedPageId = "page-1";
    private string _selectedBlockId = "block-para";
    private bool _syncing;
    private readonly List<Action> _detachers = [];

    public BoardsViewModel(IRichBoardSession session)
    {
        _session = session ?? throw new ArgumentNullException(nameof(session));
        _session.StatusChanged += (_, status) => Set("StatusText", status);
        PushDocumentToBindings();
        Set("StatusText", _session.Status);
    }

    public IRichBoardSession Session => _session;

    /// <summary>Raised after structural changes so the host can rebuild BlocksHost (never per keystroke).</summary>
    public event Action? RebuildRequested;

    /// <summary>Raised when the style editor dialog should open (host wires the Window).</summary>
    public event Action? StyleEditorRequested;

    /// <summary>Host-provided file picker: kind is "board", "image" or "attach". Null in headless tests.</summary>
    public Func<string, Task<string?>>? PickFileAsync { get; set; }

    /// <summary>Host-provided board switcher used by OpenBoard when set.</summary>
    public Func<Task>? OpenBoardAsync { get; set; }

    public string SelectedBlockId => _selectedBlockId;
    public IReadOnlyList<RichStyleView> StyleList => _session.Styles;
    public IReadOnlyList<RichBoardBlock> PageBlocks => CurrentPage().Blocks;

    public string InkTool { get; set; } = "Pen";
    public double InkWidth { get; set; } = 2.5;
    public string InkColor { get; set; } = "#FF111111";
    public double InkZoom { get; set; } = 1;
    public double InkPanX { get; set; }
    public double InkPanY { get; set; }

    public event PropertyChangedEventHandler? PropertyChanged;

    public void Set(string property, object? value, [CallerMemberName] string? caller = null)
    {
        _properties[property] = value;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(property));
    }

    public object? Get(string property) =>
        _properties.TryGetValue(property, out var val) ? val : null;

    public bool TryGetValue(string path, out object? value)
    {
        var lastDot = path.LastIndexOf('.');
        var key = lastDot >= 0 ? path[(lastDot + 1)..] : path;
        return _properties.TryGetValue(key, out value);
    }

    public string? StyleName(string styleId) =>
        _session.Styles.FirstOrDefault(s => s.Id == styleId)?.Name ?? styleId;

    public RichBoardBlock? FindBlock(string id) =>
        CurrentPage().Blocks.FirstOrDefault(b => b.Id == id);

    public void RequestRebuild() => RebuildRequested?.Invoke();

    public void RefreshAfterEdit()
    {
        PushDocumentToBindings();
        RequestRebuild();
    }

    public async ValueTask DispatchAsync(string command, object? parameter, CancellationToken cancellationToken = default)
    {
        switch (command)
        {
            case "NewBoard":
                _session.Document.Title = "Untitled board";
                _session.Document.Sections.Clear();
                _session.Document.Sections.Add(InMemoryRichBoardSession.CreateDefault().Sections[0]);
                ReselectDefaults();
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "OpenBoard":
                await OpenBoardDispatchAsync(cancellationToken);
                break;
            case "SaveBoard":
                await _session.SaveAsync(cancellationToken);
                Set("StatusText", _session.Status);
                RefreshAfterEdit();
                break;
            case "SaveAsBoard":
                var basePath = _session.FilePath ?? "memory://boards/default";
                var copyPath = basePath.EndsWith(".9to1board", StringComparison.OrdinalIgnoreCase)
                    ? basePath[..^".9to1board".Length] + " (copy).9to1board"
                    : basePath + "-copy";
                await _session.SaveAsAsync(copyPath, cancellationToken);
                PushDocumentToBindings();
                RequestRebuild();
                break;
            case "AddBlock":
                CurrentPage().Blocks.Add(new RichBoardBlock { Kind = "paragraph", Text = "New block" });
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "AddSection":
                var section = new RichBoardSection { Title = $"Section {_session.Document.Sections.Count + 1}" };
                section.Pages.Add(new RichBoardPage { Title = "New page" });
                _session.Document.Sections.Add(section);
                _selectedSectionId = section.Id;
                _selectedPageId = section.Pages[0].Id;
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "AddPage":
                var page = new RichBoardPage { Title = $"Page {CurrentSection().Pages.Count + 1}" };
                CurrentSection().Pages.Add(page);
                _selectedPageId = page.Id;
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "ToggleBold":
                SelectedBlock().Bold = !SelectedBlock().Bold;
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "ToggleItalic":
                SelectedBlock().Italic = !SelectedBlock().Italic;
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "ToggleUnderline":
                SelectedBlock().Underline = !SelectedBlock().Underline;
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "ToggleStrike":
                SelectedBlock().Strike = !SelectedBlock().Strike;
                PushDocumentToBindings();
                _session.MarkDirty();
                RequestRebuild();
                break;
            case "ToggleSub":
                ToggleBaseline("subscript");
                break;
            case "ToggleSup":
                ToggleBaseline("superscript");
                break;
            case "ClearFormat":
                ClearSelectedFormat();
                break;
            case "FontBigger":
                ScaleSelectedFont(2);
                break;
            case "FontSmaller":
                ScaleSelectedFont(-2);
                break;
            case "AlignLeft": SetSelectedAlignment("left"); break;
            case "AlignCenter": SetSelectedAlignment("center"); break;
            case "AlignRight": SetSelectedAlignment("right"); break;
            case "AlignJustify": SetSelectedAlignment("justify"); break;
            case "IndentInc": ShiftSelectedIndent(1); break;
            case "IndentDec": ShiftSelectedIndent(-1); break;
            case "Undo":
                if (await _session.UndoAsync(cancellationToken))
                    Set("StatusText", _session.Status);
                else
                    Set("StatusText", "Nothing to undo");
                ReselectAfterUndo();
                RefreshAfterEdit();
                break;
            case "Redo":
                if (await _session.RedoAsync(cancellationToken))
                    Set("StatusText", _session.Status);
                else
                    Set("StatusText", "Nothing to redo");
                ReselectAfterUndo();
                RefreshAfterEdit();
                break;
            case "ManageStyles":
                StyleEditorRequested?.Invoke();
                break;
            case "AddInkDot":
                AddInkStroke();
                break;
            case "ClearInk":
                await ClearInkAsync(cancellationToken);
                break;
            case "SelectSection1":
                if (_session.Document.Sections.Count > 0)
                {
                    _selectedSectionId = _session.Document.Sections[0].Id;
                    _selectedPageId = CurrentSection().Pages.Count > 0 ? CurrentSection().Pages[0].Id : _selectedPageId;
                    PushDocumentToBindings();
                    RequestRebuild();
                }
                break;
            case "SelectSection2":
                if (_session.Document.Sections.Count > 1)
                {
                    _selectedSectionId = _session.Document.Sections[1].Id;
                    _selectedPageId = CurrentSection().Pages.Count > 0 ? CurrentSection().Pages[0].Id : _selectedPageId;
                    PushDocumentToBindings();
                    RequestRebuild();
                }
                break;
            case "SelectPage1":
                if (CurrentSection().Pages.Count > 0)
                {
                    _selectedPageId = CurrentSection().Pages[0].Id;
                    PushDocumentToBindings();
                    RequestRebuild();
                }
                break;
            case "SelectPage2":
                if (CurrentSection().Pages.Count > 1)
                {
                    _selectedPageId = CurrentSection().Pages[1].Id;
                    PushDocumentToBindings();
                    RequestRebuild();
                }
                break;
        }
    }

    private async Task OpenBoardDispatchAsync(CancellationToken cancellationToken)
    {
        if (OpenBoardAsync is not null)
        {
            await OpenBoardAsync();
            return;
        }
        var picked = PickFileAsync is not null ? await PickFileAsync("board") : null;
        try
        {
            await _session.OpenAsync(picked ?? _session.FilePath, cancellationToken);
            ReselectDefaults();
            PushDocumentToBindings();
            RequestRebuild();
        }
        catch (Exception error)
        {
            Set("StatusText", "Open failed: " + FirstLine(error.Message));
        }
    }

    /// <summary>
    /// Wire live editing: subscribes to named TextBox/CheckBox controls built
    /// by CuiControlLoader so multiline edits update session state (dirty +
    /// debounced autosave). The loader itself only pushes one-way bindings.
    /// Dynamically rendered BlocksHost children wire their own handlers in
    /// BlockRenderer; this covers the static CUI surface.
    /// </summary>
    public void Attach(Control root)
    {
        foreach (var textBox in FindControls<TextBox>(root))
        {
            var name = textBox.Name ?? string.Empty;
            EventHandler<TextChangedEventArgs> textHandler = (_, _) =>
            {
                if (_syncing)
                    return;
                EditText(name, textBox.Text ?? string.Empty);
            };
            EventHandler<FocusChangedEventArgs> focusHandler = (_, _) =>
            {
                if (_syncing)
                    return;
                FocusBlockFromControl(name);
            };
            textBox.TextChanged += textHandler;
            textBox.GotFocus += focusHandler;
            _detachers.Add(() =>
            {
                textBox.TextChanged -= textHandler;
                textBox.GotFocus -= focusHandler;
            });
        }
        foreach (var checkBox in FindControls<CheckBox>(root))
        {
            var name = checkBox.Name ?? string.Empty;
            EventHandler<Avalonia.Interactivity.RoutedEventArgs> checkHandler = (_, _) =>
            {
                if (_syncing)
                    return;
                EditCheck(name, checkBox.IsChecked == true);
            };
            checkBox.IsCheckedChanged += checkHandler;
            _detachers.Add(() => checkBox.IsCheckedChanged -= checkHandler);
        }
        SyncControlValues(root);
    }

    /// <summary>Unsubscribe all Attach handlers (used when switching boards).</summary>
    public void Detach()
    {
        foreach (var remove in _detachers)
        {
            try { remove(); }
            catch { /* Detach is best-effort. */ }
        }
        _detachers.Clear();
    }

    /// <summary>Push current binding values into live controls without re-firing edits.</summary>
    public void SyncControlValues(Control root)
    {
        _syncing = true;
        try
        {
            foreach (var textBox in FindControls<TextBox>(root))
            {
                var value = Get(BindingForControl(textBox.Name ?? string.Empty))?.ToString();
                if (value is not null && textBox.Text != value)
                    textBox.Text = value;
            }
            foreach (var checkBox in FindControls<CheckBox>(root))
            {
                var value = Get(BindingForControl(checkBox.Name ?? string.Empty))?.ToString();
                if (value is not null && bool.TryParse(value, out var done) && checkBox.IsChecked != done)
                    checkBox.IsChecked = done;
            }
        }
        finally
        {
            _syncing = false;
        }
    }

    public void AddInkStroke(double x = 60, double y = 40)
    {
        if (_session is ContractSessionAdapter adapter)
        {
            _ = CommitSampleInkAsync(adapter);
            return;
        }
        var ink = CurrentPage().Blocks.FirstOrDefault(b => b.Kind == "ink");
        if (ink is null)
        {
            ink = new RichBoardBlock { Kind = "ink", Text = "Sketch" };
            CurrentPage().Blocks.Add(ink);
        }
        ink.InkStrokeCount++;
        PushDocumentToBindings();
        _session.MarkDirty();
        RequestRebuild();
    }

    /// <summary>Commits one pointer-drawn stroke as real persisted ink data.</summary>
    public async ValueTask CommitInkStrokeAsync(IReadOnlyList<(double X, double Y)> points)
    {
        if (_session is ContractSessionAdapter adapter)
        {
            await adapter.CommitInkStrokeAsync(points);
            PushDocumentToBindings();
            RequestRebuild();
            return;
        }
        AddInkStroke();
    }

    /// <summary>Commits one pressure-aware stroke with the selected tool/width/color.</summary>
    public async ValueTask CommitInkStrokeAsync(
        IReadOnlyList<(double X, double Y, double Pressure)> points,
        double width, string color, string tool)
    {
        if (_session is ContractSessionAdapter adapter)
        {
            await adapter.CommitInkStrokeAsync(points, width, color, tool);
            PushDocumentToBindings();
            RequestRebuild();
            return;
        }
        AddInkStroke();
    }

    public async ValueTask ClearInkAsync(CancellationToken cancellationToken = default)
    {
        if (_session is ContractSessionAdapter adapter)
        {
            await adapter.ClearInkAsync(cancellationToken);
            PushDocumentToBindings();
            RequestRebuild();
            Set("StatusText", _session.Status);
            return;
        }
        var ink = CurrentPage().Blocks.FirstOrDefault(b => b.Kind == "ink");
        if (ink is not null)
            ink.InkStrokeCount = 0;
        PushDocumentToBindings();
        _session.MarkDirty();
        RequestRebuild();
    }

    private async Task CommitSampleInkAsync(ContractSessionAdapter adapter)
    {
        await adapter.AddSampleInkStrokeAsync();
        PushDocumentToBindings();
        RequestRebuild();
    }

    // ----- Generalized id-encoded editing (legacy names keep working) -----

    public void EditText(string controlName, string text)
    {
        switch (controlName)
        {
            case "BoardTitleBox":
                _session.Document.Title = text;
                Set("BoardTitle", text);
                break;
            case "HeadingBox":
                FindOrCreateBlock("heading").Text = text;
                Set("HeadingText", text);
                break;
            case "ParaBox":
                FindOrCreateBlock("paragraph").Text = text;
                Set("ParaText", text);
                _selectedBlockId = FindOrCreateBlock("paragraph").Id;
                break;
            case "Check1Box":
                FindChecklist(0).Text = text;
                Set("Check1Text", text);
                break;
            case "Check2Box":
                FindChecklist(1).Text = text;
                Set("Check2Text", text);
                break;
            case "Cell00": SetTableCell("0,0", text); Set("Cell00", text); break;
            case "Cell01": SetTableCell("0,1", text); Set("Cell01", text); break;
            case "Cell10": SetTableCell("1,0", text); Set("Cell10", text); break;
            case "Cell11": SetTableCell("1,1", text); Set("Cell11", text); break;
            default:
                if (!EditDynamicText(controlName, text))
                    return;
                break;
        }
        _session.MarkDirty();
    }

    private bool EditDynamicText(string controlName, string text)
    {
        // t_{blockId}: paragraph/heading body.
        if (controlName.StartsWith("t_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["t_".Length..]);
            if (block is null)
                return false;
            block.Text = text;
            _selectedBlockId = block.Id;
            PushSelectedInfo();
            return true;
        }
        // chk_{parentId}_{itemId} or chk_{plainId}: checklist item text.
        if (controlName.StartsWith("chk_", StringComparison.Ordinal))
        {
            var block = FindChecklistBlock(controlName["chk_".Length..]);
            if (block is null)
                return false;
            block.Text = text;
            _selectedBlockId = block.Id;
            return true;
        }
        // cell_{blockId}_{r}_{c}: table cell text.
        if (controlName.StartsWith("cell_", StringComparison.Ordinal))
        {
            var rest = controlName["cell_".Length..].Split('_');
            if (rest.Length < 3 || !int.TryParse(rest[^2], out var row) || !int.TryParse(rest[^1], out var col))
                return false;
            var blockId = string.Join("_", rest[..^2]);
            var block = FindBlock(blockId);
            if (block is null || block.Kind != "table")
                return false;
            block.TableCells[$"{row},{col}"] = text;
            _selectedBlockId = block.Id;
            return true;
        }
        // gx_{blockId}_{exprId}: graph expression text.
        if (controlName.StartsWith("gx_", StringComparison.Ordinal))
        {
            if (!SplitBlockAndTail(controlName["gx_".Length..], out var blockId, out var exprId))
                return false;
            var expr = FindBlock(blockId)?.Graph?.Expressions.FirstOrDefault(e => e.Id == exprId);
            if (expr is null)
                return false;
            expr.Text = text;
            _selectedBlockId = blockId;
            return true;
        }
        // gc_{blockId}_{exprId}: graph expression color.
        if (controlName.StartsWith("gc_", StringComparison.Ordinal))
        {
            if (!SplitBlockAndTail(controlName["gc_".Length..], out var blockId, out var exprId))
                return false;
            var expr = FindBlock(blockId)?.Graph?.Expressions.FirstOrDefault(e => e.Id == exprId);
            if (expr is null)
                return false;
            expr.Color = text;
            return true;
        }
        // gvp_{field}_{blockId}: graph viewport doubles.
        if (controlName.StartsWith("gvp_", StringComparison.Ordinal))
            return EditViewportField(controlName["gvp_".Length..], text);
        // iw_{blockId} / ialt_{blockId}: image width / alt text.
        if (controlName.StartsWith("iw_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["iw_".Length..]);
            if (block?.Image is null)
                return false;
            if (double.TryParse(text, out var width) && width is >= 0 and <= 8000)
                block.Image.Width = width;
            return true;
        }
        if (controlName.StartsWith("ialt_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["ialt_".Length..]);
            if (block?.Image is null)
                return false;
            block.Image.AltText = text;
            return true;
        }
        // dvth_{blockId} / dvcl_{blockId}: divider thickness / color.
        if (controlName.StartsWith("dvth_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["dvth_".Length..]);
            if (block?.Divider is null)
                return false;
            if (double.TryParse(text, out var thickness) && thickness is > 0 and <= 64)
                block.Divider.Thickness = thickness;
            return true;
        }
        if (controlName.StartsWith("dvcl_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["dvcl_".Length..]);
            if (block?.Divider is null)
                return false;
            block.Divider.Color = text;
            return true;
        }
        // inkwidth / inkcolor: session-level ink defaults (static names).
        if (controlName == "InkWidthBox")
        {
            if (double.TryParse(text, out var width) && width is > 0 and <= 64)
                InkWidth = width;
            return true;
        }
        if (controlName == "InkColorBox")
        {
            if (!string.IsNullOrWhiteSpace(text))
                InkColor = text.Trim();
            return true;
        }
        return false;
    }

    private bool EditViewportField(string rest, string text)
    {
        // rest = {field}_{blockId}; block ids never contain '_' from the contract.
        var cut = rest.LastIndexOf('_');
        if (cut <= 0)
            return false;
        var field = rest[..cut];
        var blockId = rest[(cut + 1)..];
        var graph = FindBlock(blockId)?.Graph;
        if (graph is null || !double.TryParse(text, out var value) || !double.IsFinite(value))
            return false;
        switch (field.ToLowerInvariant())
        {
            case "xmin": graph.XMin = value; break;
            case "xmax": graph.XMax = value; break;
            case "ymin": graph.YMin = value; break;
            case "ymax": graph.YMax = value; break;
            default: return false;
        }
        _selectedBlockId = blockId;
        return true;
    }

    public void EditCheck(string controlName, bool done)
    {
        switch (controlName)
        {
            case "Check1Done": FindChecklist(0).IsChecked = done; Set("Check1Done", done); break;
            case "Check2Done": FindChecklist(1).IsChecked = done; Set("Check2Done", done); break;
            default:
                if (!EditDynamicCheck(controlName, done))
                    return;
                break;
        }
        _session.MarkDirty();
    }

    private bool EditDynamicCheck(string controlName, bool done)
    {
        // done_{parentId}_{itemId} or done_{plainId}.
        if (controlName.StartsWith("done_", StringComparison.Ordinal))
        {
            var block = FindChecklistBlock(controlName["done_".Length..]);
            if (block is null)
                return false;
            block.IsChecked = done;
            _selectedBlockId = block.Id;
            return true;
        }
        // gv_{blockId}_{exprId}: graph expression visibility.
        if (controlName.StartsWith("gv_", StringComparison.Ordinal))
        {
            if (!SplitBlockAndTail(controlName["gv_".Length..], out var blockId, out var exprId))
                return false;
            var expr = FindBlock(blockId)?.Graph?.Expressions.FirstOrDefault(e => e.Id == exprId);
            if (expr is null)
                return false;
            expr.Visible = done;
            _selectedBlockId = blockId;
            return true;
        }
        return false;
    }

    public void FocusBlock(string blockId)
    {
        if (FindBlock(blockId) is null)
            return;
        _selectedBlockId = blockId;
        PushSelectedInfo();
    }

    private void FocusBlockFromControl(string controlName)
    {
        var legacy = controlName switch
        {
            "HeadingBox" => FindOrCreateBlock("heading").Id,
            "ParaBox" => FindOrCreateBlock("paragraph").Id,
            "Check1Box" or "Check1Done" => FindChecklist(0).Id,
            "Check2Box" or "Check2Done" => FindChecklist(1).Id,
            "Cell00" or "Cell01" or "Cell10" or "Cell11" => FindOrCreateBlock("table").Id,
            _ => null,
        };
        if (legacy is not null)
        {
            FocusBlock(legacy);
            return;
        }
        if (controlName.StartsWith("t_", StringComparison.Ordinal))
            FocusBlock(controlName["t_".Length..]);
        else if (controlName.StartsWith("chk_", StringComparison.Ordinal)
            || controlName.StartsWith("done_", StringComparison.Ordinal))
        {
            var tail = controlName[(controlName.IndexOf('_') + 1)..];
            var block = FindChecklistBlock(tail);
            if (block is not null)
                FocusBlock(block.Id);
        }
        else if (controlName.StartsWith("cell_", StringComparison.Ordinal))
        {
            var rest = controlName["cell_".Length..].Split('_');
            if (rest.Length >= 3)
                FocusBlock(string.Join("_", rest[..^2]));
        }
    }

    // ----- Block operations used by BlockRenderer -----

    public async Task InsertKindAsync(string kindTag)
    {
        if (kindTag.StartsWith("style:", StringComparison.Ordinal))
        {
            await ApplyStyleToSelectedAsync(kindTag["style:".Length..]);
            return;
        }
        var page = CurrentPage();
        RichBoardBlock block = kindTag switch
        {
            "heading" => new RichBoardBlock { Kind = "heading", Text = "New heading" },
            "checklist" => new RichBoardBlock { Kind = "checklist", Text = "New item" },
            "table" => new RichBoardBlock
            {
                Kind = "table", Text = "New table", TableRows = 2, TableCols = 2,
                TableCells = new Dictionary<string, string>(StringComparer.Ordinal)
                {
                    ["0,0"] = string.Empty, ["0,1"] = string.Empty,
                    ["1,0"] = string.Empty, ["1,1"] = string.Empty,
                },
            },
            "image" => new RichBoardBlock
            {
                Kind = "image", Text = "image",
                Image = new RichImageView { DisplayName = "image (choose a file)", MediaType = "image/png" },
            },
            "divider" => new RichBoardBlock
            {
                Kind = "divider",
                Divider = new RichDividerView { Thickness = 1, LineStyle = "solid", Color = "#FF5F6368" },
            },
            "graph" => new RichBoardBlock
            {
                Kind = "graph",
                Graph = new RichGraphView
                {
                    Expressions = [new RichGraphExpressionView { Text = "y = x" }],
                    XMin = -10, XMax = 10, YMin = -10, YMax = 10,
                },
            },
            _ => new RichBoardBlock { Kind = "paragraph", Text = "New block" },
        };
        page.Blocks.Add(block);
        _selectedBlockId = block.Id;
        PushDocumentToBindings();
        _session.MarkDirty();
        if (kindTag == "image")
            Set("StatusText", "Image block added — use Replace to choose a file");
        RequestRebuild();
        if (kindTag == "image")
            await ReplaceImageAsync(block.Id);
    }

    public async Task ApplyStyleToSelectedAsync(string styleId)
    {
        if (string.IsNullOrWhiteSpace(styleId))
            return;
        if (!_session.Styles.Any(s => s.Id == styleId))
        {
