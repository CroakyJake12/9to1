    /// <summary>
    /// Splits a checklist/bulleted/numbered row at the caret into two same-kind rows,
    /// the new one placed immediately after the original. Empty rows keep the existing
    /// Enter behaviour of adding the next row. Uses the app projection + MarkDirty route,
    /// the same supported structural-edit path as the insert menu.
    /// </summary>
    private void SplitListItemAt(RichBoardPage page, RichBoardBlock block, int caretIndex)
    {
        var text = block.Text ?? string.Empty;
        var index = page.Blocks.IndexOf(block);
        var caret = Math.Clamp(caretIndex, 0, text.Length);
        if (caret <= 0 || caret >= text.Length)
        {
            // Enter at the end (or start of an empty row) adds the next row after this one.
            var next = new RichBoardBlock
            {
                Kind = block.Kind,
                Text = string.Empty,
                Level = block.Level,
                StyleId = block.StyleId,
                Layout = block.Layout,
            };
            page.Blocks.Insert(index + 1, next);
            _selectedBlockId = next.Id;
            PushDocumentToBindings();
            _session.MarkDirty();
            RequestRebuild();
            return;
        }
        var tail = text[caret..];
        BoardTextRanges.ReplaceText(block, text[..caret]);
        var sibling = new RichBoardBlock
        {
            Kind = block.Kind,
            Text = tail,
            Level = block.Level,
            StyleId = block.StyleId,
            Layout = block.Layout,
        };
        page.Blocks.Insert(index + 1, sibling);
        _selectedBlockId = sibling.Id;
        PushDocumentToBindings();
        _session.MarkDirty();
        RequestRebuild();
    }

    public async Task<bool> SplitTextBlockAtAsync(string blockId, int caretIndex,
        CancellationToken cancellationToken = default)
    {
        if (!RequireEditMode()) return false;
        var page = CurrentPage();
        var block = page.Blocks.FirstOrDefault(item => item.Id == blockId);
        if (block is null) return false;
        // UX27-BOARD-016/017: Enter inside a list row splits that row into a same-kind
        // sibling immediately after it. The renderer draws checklist, bulleted and
        // numbered rows through one row builder, so all three share this behaviour.
        if (IsListKind(block.Kind))
        {
            SplitListItemAt(page, block, caretIndex);
            return true;
        }
        if (block.Kind is not ("paragraph" or "heading"))
        {
            Set("StatusText", $"A {block.Kind} block is not split by Enter. Use its own editor controls.");
            return false;
        }
        if (caretIndex < 0 || caretIndex > block.Text.Length) return false;
        if (block.Runs.Count > 0 && !string.Equals(string.Concat(block.Runs.Select(run => run.Text)), block.Text, StringComparison.Ordinal))
        {
            Set("StatusText", "Text block formatting ranges do not match its text; the block was left unchanged.");
            return false;
        }

        string createdId;
        if (_session is ContractSessionAdapter adapter)
        {
            try { createdId = await adapter.SplitTextBlockAtAsync(page.Id, blockId, caretIndex, cancellationToken); }
            catch (Exception error) when (error is InvalidOperationException or ArgumentOutOfRangeException or KeyNotFoundException)
            {
                Set("StatusText", "Text block could not be split: " + FirstLine(error.Message));
                return false;
            }
        }
        else
        {
            var text = block.Text;
            var (leftRuns, rightRuns) = BoardTextRanges.SplitAt(block.Runs, text, caretIndex);
            block.Text = text[..caretIndex];
            block.Runs = leftRuns;
            var following = new RichBoardBlock
            {
                Kind = block.Kind,
                StyleId = block.StyleId,
                Text = text[caretIndex..],
                Runs = rightRuns,
                Alignment = block.Alignment,
                LineSpacing = block.LineSpacing,
                SpaceBefore = block.SpaceBefore,
                SpaceAfter = block.SpaceAfter,
                IndentLevel = block.IndentLevel,
            };
            page.Blocks.Insert(page.Blocks.IndexOf(block) + 1, following);
            createdId = following.Id;
            _session.MarkDirty();
        }
        _selectedBlockId = createdId;
        _pendingTextFocus = (page.Id, createdId, 0);
        PushDocumentToBindings();
        RequestRebuild();
        return true;
    }

    public async Task<bool> MergeTextBlockWithPreviousAsync(string blockId,
        CancellationToken cancellationToken = default)
    {
        if (!RequireEditMode()) return false;
        var page = CurrentPage();
        var index = page.Blocks.FindIndex(item => item.Id == blockId);
        if (index <= 0) return false;
        var previous = page.Blocks[index - 1];
        var current = page.Blocks[index];
        if (previous.Kind is not ("paragraph" or "heading") || current.Kind is not ("paragraph" or "heading"))
            return false;
        if ((previous.Runs.Count > 0 && !string.Equals(string.Concat(previous.Runs.Select(run => run.Text)), previous.Text, StringComparison.Ordinal)) ||
            (current.Runs.Count > 0 && !string.Equals(string.Concat(current.Runs.Select(run => run.Text)), current.Text, StringComparison.Ordinal)))
        {
            Set("StatusText", "Text block formatting ranges do not match its text; the blocks were left unchanged.");
            return false;
        }
        var caretIndex = previous.Text.Length;
        string mergedId;
        if (_session is ContractSessionAdapter adapter)
        {
            try { mergedId = await adapter.MergeTextBlockWithPreviousAsync(page.Id, blockId, cancellationToken); }
            catch (Exception error) when (error is InvalidOperationException or ArgumentOutOfRangeException or KeyNotFoundException)
            {
                Set("StatusText", "Text blocks could not be merged: " + FirstLine(error.Message));
                return false;
            }
        }
        else
        {
            previous.Text += current.Text;
            if (previous.Runs.Count > 0 || current.Runs.Count > 0)
                previous.Runs = [.. BoardTextRanges.Copy(previous.Runs), .. BoardTextRanges.Copy(current.Runs)];
            page.Blocks.RemoveAt(index);
            _session.MarkDirty();
            mergedId = previous.Id;
        }
        _selectedBlockId = mergedId;
        _pendingTextFocus = (page.Id, mergedId, caretIndex);
        PushDocumentToBindings();
        RequestRebuild();
        return true;
    }

    internal bool TryConsumePendingTextFocus(string pageId, string blockId, out int caretIndex)
    {
        if (_pendingTextFocus is { } pending && pending.PageId == pageId && pending.BlockId == blockId)
        {
            caretIndex = pending.CaretIndex;
            _pendingTextFocus = null;
            return true;
        }
        caretIndex = 0;
        return false;
    }

    public void EditText(string controlName, string text)
    {
        if (_disposed || SessionIsDisposed) return;
        if (!_isEditMode && controlName != "NavSearchBox") return;
        switch (controlName)
        {
            case "BoardTitleBox":
                if (string.Equals(_session.Document.Title, text, StringComparison.Ordinal)) return;
                _session.Document.Title = text;
                Set("BoardTitle", text);
                RefreshPageBreadcrumb();
                _session.MarkDirty();
                break;
            case "PageTitleBox":
            {
                var pageTitle = text.Length <= 2048 ? text : text[..2048];
                var page = CurrentPage();
                if (string.Equals(page.Title, pageTitle, StringComparison.Ordinal)) return;
                page.Title = pageTitle;
                Set("PageTitle", pageTitle);
                RefreshPageBreadcrumb();
                NavRebuildRequested?.Invoke();
                _session.MarkDirty();
                break;
            }
            case "NavSearchBox":
                // Filter-only: never dirties the document.
                SearchText = text;
                return;
            case "HeadingBox":
                BoardTextRanges.ReplaceText(FindOrCreateBlock("heading"), text);
                Set("HeadingText", text);
                break;
            case "ParaBox":
                BoardTextRanges.ReplaceText(FindOrCreateBlock("paragraph"), text);
                Set("ParaText", text);
                _selectedBlockId = FindOrCreateBlock("paragraph").Id;
                break;
            case "Check1Box":
                FindChecklist(0).Text = text;
                Set("Check1Text", text);
                break;
            case "Check2Box":
                FindChecklist(1).Text = text;
                Set("Check2Text", text);
                break;
            case "Cell00": SetTableCell("0,0", text); Set("Cell00", text); break;
            case "Cell01": SetTableCell("0,1", text); Set("Cell01", text); break;
            case "Cell10": SetTableCell("1,0", text); Set("Cell10", text); break;
            case "Cell11": SetTableCell("1,1", text); Set("Cell11", text); break;
            default:
                if (!EditDynamicText(controlName, text))
                    return;
                break;
        }
        _session.MarkDirty();
        RefreshTextPresentations();
    }

    private bool EditDynamicText(string controlName, string text)
    {
        // t_{blockId}: paragraph/heading body.
        if (controlName.StartsWith("t_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["t_".Length..]);
            if (block is null)
                return false;
            BoardTextRanges.ReplaceText(block, text);
            _selectedBlockId = block.Id;
            PushSelectedInfo();
            return true;
        }
        // chk_{parentId}_{itemId} or chk_{plainId}: checklist item text.
        if (controlName.StartsWith("chk_", StringComparison.Ordinal))
        {
            var block = FindChecklistBlock(controlName["chk_".Length..]);
            if (block is null)
                return false;
            block.Text = text;
            _selectedBlockId = block.Id;
            return true;
        }
        // cell_{blockId}_{r}_{c}: table cell text.
        if (controlName.StartsWith("cell_", StringComparison.Ordinal))
        {
            var rest = controlName["cell_".Length..].Split('_');
            if (rest.Length < 3 || !int.TryParse(rest[^2], out var row) || !int.TryParse(rest[^1], out var col))
                return false;
            var blockId = string.Join("_", rest[..^2]);
            var block = FindBlock(blockId);
            if (block is null || block.Kind != "table")
                return false;
            block.TableCells[$"{row},{col}"] = text;
            _selectedBlockId = block.Id;
            return true;
        }
        // gx_{blockId}_{exprId}: graph expression text.
        if (controlName.StartsWith("gx_", StringComparison.Ordinal))
        {
            if (!SplitBlockAndTail(controlName["gx_".Length..], out var blockId, out var exprId))
                return false;
            var expr = FindBlock(blockId)?.Graph?.Expressions.FirstOrDefault(e => e.Id == exprId);
            if (expr is null)
                return false;
            expr.Text = text;
            _selectedBlockId = blockId;
            return true;
        }
        // gc_{blockId}_{exprId}: graph expression color.
        if (controlName.StartsWith("gc_", StringComparison.Ordinal))
        {
            if (!SplitBlockAndTail(controlName["gc_".Length..], out var blockId, out var exprId))
                return false;
            var expr = FindBlock(blockId)?.Graph?.Expressions.FirstOrDefault(e => e.Id == exprId);
            if (expr is null)
                return false;
            expr.Color = text;
            return true;
        }
        // gvp_{field}_{blockId}: graph viewport doubles.
        if (controlName.StartsWith("gvp_", StringComparison.Ordinal))
            return EditViewportField(controlName["gvp_".Length..], text);
        // iw_{blockId} / ialt_{blockId}: image width / alt text.
        if (controlName.StartsWith("iw_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["iw_".Length..]);
            if (block?.Image is null)
                return false;
            if (double.TryParse(text, out var width) && width is >= 0 and <= 8000)
                block.Image.Width = width;
            return true;
        }
        if (controlName.StartsWith("ialt_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["ialt_".Length..]);
            if (block?.Image is null)
                return false;
            block.Image.AltText = text;
            return true;
        }
        // dvth_{blockId} / dvcl_{blockId}: divider thickness / color.
        if (controlName.StartsWith("dvth_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["dvth_".Length..]);
            if (block?.Divider is null)
                return false;
            if (double.TryParse(text, out var thickness) && thickness is > 0 and <= 64)
                block.Divider.Thickness = thickness;
            return true;
        }
        if (controlName.StartsWith("dvcl_", StringComparison.Ordinal))
        {
            var block = FindBlock(controlName["dvcl_".Length..]);
            if (block?.Divider is null)
                return false;
            block.Divider.Color = text;
            return true;
        }
        // inkwidth / inkcolor: session-level ink defaults (static names).
        if (controlName == "InkWidthBox")
        {
            if (double.TryParse(text, out var width) && width is > 0 and <= 64)
                InkWidth = width;
            return true;
        }
        if (controlName == "InkColorBox")
        {
            if (!string.IsNullOrWhiteSpace(text))
                InkColor = text.Trim();
            return true;
        }
        return false;
    }

    private bool EditViewportField(string rest, string text)
    {
        // rest = {field}_{blockId}; block ids never contain '_' from the contract.
        var cut = rest.LastIndexOf('_');
        if (cut <= 0)
            return false;
        var field = rest[..cut];
        var blockId = rest[(cut + 1)..];
        var graph = FindBlock(blockId)?.Graph;
        if (graph is null || !double.TryParse(text, out var value) || !double.IsFinite(value))
            return false;
        switch (field.ToLowerInvariant())
        {
            case "xmin": graph.XMin = value; break;
            case "xmax": graph.XMax = value; break;
            case "ymin": graph.YMin = value; break;
            case "ymax": graph.YMax = value; break;
            default: return false;
        }
        _selectedBlockId = blockId;
        return true;
    }

