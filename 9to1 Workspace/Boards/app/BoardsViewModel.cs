    /// <summary>
    /// Wire live editing: subscribes to named TextBox/CheckBox controls built
    /// by CuiControlLoader so multiline edits update session state (dirty +
    /// debounced autosave). The loader itself only pushes one-way bindings.
    /// Dynamically rendered BlocksHost children wire their own handlers in
    /// BlockRenderer; this covers the static CUI surface.
    /// </summary>
    public void Attach(Control root)
    {
        _attachedRoot = root;
        _textRangeDetached = false;
        ApplyAuthoringState(root);
        foreach (var textBox in FindControls<TextBox>(root))
        {
            var name = textBox.Name ?? string.Empty;
            EventHandler<TextChangedEventArgs> textHandler = (_, _) =>
            {
                if (_syncing || _disposed || !ReferenceEquals(_attachedRoot, root) || _textRangeDetached)
                    return;
                EditText(name, textBox.Text ?? string.Empty);
            };
            EventHandler<FocusChangedEventArgs> focusHandler = (_, _) =>
            {
                if (_syncing || _disposed || !ReferenceEquals(_attachedRoot, root) || _textRangeDetached)
                    return;
                FocusBlockFromControl(name);
            };
            textBox.TextChanged += textHandler;
            textBox.GotFocus += focusHandler;
            _detachers.Add(() =>
            {
                textBox.TextChanged -= textHandler;
                textBox.GotFocus -= focusHandler;
            });
        }
        foreach (var checkBox in FindControls<CheckBox>(root))
        {
            var name = checkBox.Name ?? string.Empty;
            EventHandler<Avalonia.Interactivity.RoutedEventArgs> checkHandler = (_, _) =>
            {
                if (_syncing)
                    return;
                EditCheck(name, checkBox.IsChecked == true);
            };
            checkBox.IsCheckedChanged += checkHandler;
            _detachers.Add(() => checkBox.IsCheckedChanged -= checkHandler);
        }
        SyncControlValues(root);
    }

    /// <summary>Unsubscribe all Attach handlers (used when switching boards).</summary>
    public void Detach()
    {
        _attachedRoot = null;
        _textRangeDetached = true;
        Interlocked.Increment(ref _textRangeEpoch);
        foreach (var removeRange in _textRangeBindings.Values.ToArray()) removeRange();
        _textRangeBindings.Clear();
        _textRangeControl = null;

        foreach (var remove in _detachers)
        {
            try { remove(); }
            catch { /* Detach is best-effort. */ }
        }
        _detachers.Clear();
    }

    /// <summary>Ends this editor lifetime after queued UI events have been drained.</summary>
    public void Dispose()
    {
        if (_disposed) return;
        _disposed = true;
        CancelSectionIconSuggestion();
        Detach();
    }

    /// <summary>Push current binding values into live controls without re-firing edits.</summary>
    public void SyncControlValues(Control root)
    {
        _syncing = true;
        try
        {
            foreach (var textBox in FindControls<TextBox>(root))
            {
                var value = Get(BindingForControl(textBox.Name ?? string.Empty))?.ToString();
                if (value is not null && textBox.Text != value)
                    textBox.Text = value;
            }
            foreach (var checkBox in FindControls<CheckBox>(root))
            {
                var value = Get(BindingForControl(checkBox.Name ?? string.Empty))?.ToString();
