    private static RichBoardSection CloneSection(RichBoardSection source)
    {
        var json = System.Text.Json.JsonSerializer.Serialize(source);
        var copy = System.Text.Json.JsonSerializer.Deserialize<RichBoardSection>(json) ?? new RichBoardSection();
        copy.Id = Guid.NewGuid().ToString("N");
        copy.Title = source.Title + " copy";
        foreach (var page in copy.Pages)
            FreshPageCloneIds(page);
        return copy;
    }

    private static RichBoardPage ClonePage(RichBoardPage source)
    {
        var json = System.Text.Json.JsonSerializer.Serialize(source);
        var copy = System.Text.Json.JsonSerializer.Deserialize<RichBoardPage>(json) ?? new RichBoardPage();
        FreshPageCloneIds(copy);
        copy.Title = source.Title + " copy";
        return copy;
    }

    private static void FreshPageCloneIds(RichBoardPage page)
    {
        page.Id = Guid.NewGuid().ToString("N");
        foreach (var block in page.Blocks)
        {
            var parts = block.Id.Split(':');
            block.Id = parts.Length > 1
                ? parts[0] + ":" + Guid.NewGuid().ToString("N")
                : Guid.NewGuid().ToString("N");
        }
    }

    private void FocusBlockFromControl(string controlName)
    {
        var legacy = controlName switch
        {
            "HeadingBox" => FindOrCreateBlock("heading").Id,
            "ParaBox" => FindOrCreateBlock("paragraph").Id,
            "Check1Box" or "Check1Done" => FindChecklist(0).Id,
            "Check2Box" or "Check2Done" => FindChecklist(1).Id,
            "Cell00" or "Cell01" or "Cell10" or "Cell11" => FindOrCreateBlock("table").Id,
            _ => null,
        };
        if (legacy is not null)
        {
            FocusBlock(legacy);
            return;
        }
        if (controlName.StartsWith("t_", StringComparison.Ordinal))
            FocusBlock(controlName["t_".Length..]);
        else if (controlName.StartsWith("chk_", StringComparison.Ordinal)
            || controlName.StartsWith("done_", StringComparison.Ordinal))
        {
            var tail = controlName[(controlName.IndexOf('_') + 1)..];
            var block = FindChecklistBlock(tail);
            if (block is not null)
                FocusBlock(block.Id);
        }
        else if (controlName.StartsWith("cell_", StringComparison.Ordinal))
        {
            var rest = controlName["cell_".Length..].Split('_');
            if (rest.Length >= 3 &&
                int.TryParse(rest[^2], out var row) && int.TryParse(rest[^1], out var col))
                FocusCell(string.Join("_", rest[..^2]), row, col);
        }
    }

    internal void FocusCell(string blockId, int row, int column)
    {
        var block = FindBlock(blockId);
        if (block?.Kind != "table" || row < 0 || row >= block.TableRows || column < 0 || column >= block.TableCols)
            return;
        FocusBlock(blockId);
        InvalidateTableSelection();
        SelectedCell = (blockId, row, column);
        RefreshCuiContext();
        SelectionChanged?.Invoke();
    }

