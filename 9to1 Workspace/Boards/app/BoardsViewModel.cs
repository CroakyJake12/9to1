    /// <summary>Checklist item ids are "parentId:itemId"; plain ids address the block itself.</summary>
    private RichBoardBlock? FindChecklistBlock(string tail)
    {
        var page = CurrentPage();
        var direct = page.Blocks.FirstOrDefault(b => b.Id == tail);
        if (direct is not null)
            return IsListKind(direct.Kind) ? direct : null;
        var cut = tail.LastIndexOf('_');
        if (cut <= 0)
            return null;
        var viewId = tail[..cut] + ":" + tail[(cut + 1)..];
        return page.Blocks.FirstOrDefault(b => b.Id == viewId && IsListKind(b.Kind));
    }

    /// <summary>
    /// The renderer draws checklist, bulleted and numbered rows through the same row
    /// builder, so their edits and Enter handling must resolve every list kind.
    /// Restricting this to "checklist" silently dropped text typed in a bulleted or
    /// numbered row and turned Enter into a checkbox item.
    /// </summary>
    private static bool IsListKind(string kind) =>
        kind is "checklist" or "bulleted" or "numbered";

    private static (string? ParentId, string ItemId) SplitItemId(string viewBlockId)
    {
        var colon = viewBlockId.IndexOf(':');
        return colon > 0
            ? (viewBlockId[..colon], viewBlockId[(colon + 1)..])
            : (null, viewBlockId);
    }

    private static string ParentKey(string viewBlockId)
    {
        var (parentId, _) = SplitItemId(viewBlockId);
        return parentId ?? viewBlockId;
    }

    private static bool SplitBlockAndTail(string rest, out string blockId, out string tail)
    {
        // Contract block ids never contain '_'; expr ids ("expr-*") neither.
        var cut = rest.LastIndexOf('_');
        if (cut <= 0)
        {
            blockId = string.Empty;
            tail = string.Empty;
            return false;
        }
        blockId = rest[..cut];
        tail = rest[(cut + 1)..];
        return true;
    }

    private static string ToContractBlockId(RichBoardBlock block)
    {
        var (parentId, _) = SplitItemId(block.Id);
        return parentId ?? block.Id;
    }

    private static void EnsureTableDims(RichBoardBlock block)
    {
        if (block.TableRows <= 0)
            block.TableRows = Math.Max(1, block.TableCells.Keys.Select(RowOf).DefaultIfEmpty(0).Max() + 1);
        if (block.TableCols <= 0)
            block.TableCols = Math.Max(1, block.TableCells.Keys.Select(ColOf).DefaultIfEmpty(0).Max() + 1);
    }

    private static int RowOf(string key)
    {
        var cut = key.IndexOf(',');
        return cut > 0 && int.TryParse(key[..cut], out var row) ? row : 0;
    }

    private static int ColOf(string key)
    {
        var cut = key.IndexOf(',');
        return cut >= 0 && int.TryParse(key[(cut + 1)..], out var col) ? col : 0;
    }

